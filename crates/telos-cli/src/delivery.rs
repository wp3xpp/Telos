//! Thin operator client for the existing delivery main flow. All writes go to the daemon.
use anyhow::{ensure, Context, Result};
use serde::Deserialize;
use serde_json::{json, Value};
use std::{io::Read, path::Path, time::Duration};
use telos_core::{Contract, LoopKind, ProjectExecutionPolicy, Sandbox, VerificationPlan};
use telos_runtime::daemon::{self, Request};

#[derive(Deserialize)]
#[serde(deny_unknown_fields)]
pub struct DeliveryPackage {
    pub project_id: String,
    pub name: String,
    pub contract: Contract,
    pub verification: VerificationPlan,
    #[serde(default = "default_base")]
    pub base: String,
}
fn default_base() -> String {
    "HEAD".into()
}

fn load(path: &Path) -> Result<DeliveryPackage> {
    let file = std::fs::File::open(path).context("open delivery package")?;
    ensure!(
        file.metadata()?.is_file(),
        "delivery package must be a regular file"
    );
    let mut bytes = Vec::new();
    file.take(1024 * 1024 + 1).read_to_end(&mut bytes)?;
    ensure!(bytes.len() <= 1024 * 1024, "delivery package exceeds 1MiB");
    let package: DeliveryPackage = serde_json::from_slice(&bytes)?;
    package.contract.validate(LoopKind::Delivery)?;
    package.verification.validate(&package.contract)?;
    telos_runtime::verification_adapters::validate_plan(&package.verification)?;
    ensure!(!package.name.trim().is_empty(), "delivery name required");
    ensure!(
        package.base == "HEAD"
            || ([40, 64].contains(&package.base.len())
                && package.base.bytes().all(|b| b.is_ascii_hexdigit())),
        "base must be HEAD or a complete commit hash"
    );
    Ok(package)
}

pub async fn submit(state: &Path, file: &Path, wait: bool, wait_seconds: u64) -> Result<Value> {
    validate_wait(wait_seconds)?;
    let package = load(file)?;
    let capabilities = daemon::call(state, &Request::Ping).await?;
    validate_capabilities(&package.verification, &capabilities)?;
    // Existing project grants are prerequisites, never generated by this entry point.
    let project = daemon::call(
        state,
        &Request::InspectProject {
            id: package.project_id.clone(),
        },
    )
    .await?;
    let policy: ProjectExecutionPolicy =
        serde_json::from_value(project["execution_policy"]["policy"].clone())
            .context("project needs an existing execution policy")?;
    ensure!(
        policy.enabled && policy.sandbox == Sandbox::WorkspaceWrite,
        "project needs an existing enabled workspace-write policy"
    );
    let policy_revision = project["execution_policy"]["revision"]
        .as_i64()
        .context("project policy revision missing")?;
    eprintln!("Creating delivery: {}", package.name);
    let goal = daemon::call(
        state,
        &Request::CreateLoop {
            project_id: package.project_id,
            name: package.name,
            kind: LoopKind::Delivery,
            contract: package.contract,
        },
    )
    .await?;
    let id = goal["id"]
        .as_str()
        .context("created goal ID missing")?
        .to_owned();
    eprintln!("Goal: {id}");
    let result = async {
        eprintln!("Preparing independent workspace...");
        let workspace = daemon::call(state, &Request::PrepareWorkspace {id:id.clone(), revision:1,
            policy_revision, base:package.base}).await?;
        eprintln!("Configuring independent acceptance...");
        daemon::call(state, &Request::ConfigureVerification {id:id.clone(), revision:1,
            expected_version:0, plan:package.verification}).await?;
        let queued = daemon::call(state, &Request::StartLoop {id:id.clone(), revision:1,
            request_key:"delivery-entry-v1".into()}).await?;
        eprintln!("Queued. Background execution continues independently of this terminal.");
        if wait { follow(state, &id, wait_seconds, false).await }
        else { Ok(json!({"loop_id":id,"state":"queued","workspace":workspace,"execution":queued,
            "verification":"pending","follow_argv":["telos","--state-dir",state,"follow","--id",id]})) }
    }.await;
    result.with_context(|| {
        format!("delivery {id}; inspect or follow this goal rather than submitting another copy")
    })
}

fn validate_capabilities(plan: &VerificationPlan, capabilities: &Value) -> Result<()> {
    ensure!(
        capabilities.get("mode").is_none(),
        "daemon is not in normal execution mode"
    );
    for check in &plan.test_checks {
        // Older daemons only implement the original command adapter.
        let supported = capabilities["verification_adapters"]
            .as_array()
            .map_or(check.adapter == "local.sandbox_command", |ids| {
                ids.iter().any(|id| id.as_str() == Some(&check.adapter))
            });
        ensure!(
            supported,
            "installed daemon does not support verifier {}; upgrade it before submission",
            check.adapter
        );
    }
    Ok(())
}

fn validate_wait(seconds: u64) -> Result<()> {
    ensure!(
        (1..=86400).contains(&seconds),
        "wait-seconds must be 1..86400"
    );
    Ok(())
}

/// Observe one persisted goal. Never dispatches work, repeats a test or changes permissions.
pub async fn follow(state: &Path, id: &str, wait_seconds: u64, once: bool) -> Result<Value> {
    validate_wait(wait_seconds)?;
    let started = tokio::time::Instant::now();
    let mut previous = String::new();
    loop {
        let goal = daemon::call(state, &Request::GetLoop { id: id.into() }).await?;
        let revision = goal["revision"].as_i64().context("goal revision missing")?;
        let context = daemon::call(
            state,
            &Request::LoopContext {
                id: id.into(),
                revision,
            },
        )
        .await?;
        let schedule = daemon::call(state, &Request::ScheduleStatus { id: id.into() }).await?;
        let state_name = goal["state"].as_str().context("goal state missing")?;
        let verification_not_passed = context["latest_verification"]["results"]
            .as_array()
            .is_some_and(|results| {
                results
                    .iter()
                    .any(|r| matches!(r["verdict"].as_str(), Some("failed" | "error")))
            });
        let execution = context["recent_execution"]
            .as_array()
            .and_then(|items| items.first());
        let execution_state = execution.and_then(|item| item["state"].as_str());
        let mut stage = progress_stage(
            state_name,
            verification_not_passed,
            execution_state,
            &schedule,
            goal["kind"] == "continuous"
                && context.get("active_cycle_id") == Some(&Value::Null)
                && schedule["armed"] == true,
        );
        if state_name == "active" && context["progress"]["verification_pending"] == true {
            stage = "verifying";
        }
        if state_name == "active"
            && (context["progress"]["execution_in_flight"] == true
                || context["progress"]["repair_pending"] == true)
        {
            stage = if verification_not_passed && goal["kind"] == "continuous" {
                "diagnosing"
            } else if verification_not_passed {
                "correcting"
            } else {
                "working"
            };
        }
        if stage != previous {
            eprintln!("{id}: {stage}");
            previous = stage.into();
        }
        let finished = matches!(
            stage,
            "completed"
                | "paused"
                | "stopped"
                | "blocked"
                | "verification_not_passed"
                | "execution_not_completed"
        );
        let timed_out = started.elapsed() >= Duration::from_secs(wait_seconds);
        if once || finished || timed_out {
            let delivery = daemon::call(
                state,
                &Request::DeliveryResult {
                    id: id.into(),
                    revision,
                },
            )
            .await?;
            return Ok(
                json!({"loop_id":id,"state":stage,"loop_state":state_name,"revision":revision,
                "wait_timed_out":timed_out && !finished && !once,"snapshot_only":once,"elapsed_seconds":started.elapsed().as_secs(),
                "elapsed":telos_core::duration::format_duration_seconds(started.elapsed().as_secs()),
                "latest_execution":execution,"latest_verification":context["latest_verification"],"delivery":delivery,
                "progress":context["progress"],"schedule":schedule,"project_observations":context["project_observations"],
                "active_cycle_id":context["active_cycle_id"],"remediation_links":context["remediation_links"],
                "note":"Waiting does not cancel or restart work. An unfinished verdict may be followed by background correction; follow again to inspect progress."}),
            );
        }
        tokio::time::sleep(Duration::from_secs(1)).await;
    }
}

// Progress reflects managed work; observation receipts are returned separately.
fn progress_stage<'a>(
    state: &'a str,
    verification_not_passed: bool,
    execution: Option<&str>,
    _schedule: &Value,
    continuous_waiting: bool,
) -> &'a str {
    if matches!(state, "completed" | "paused" | "stopped" | "blocked") {
        state
    } else if verification_not_passed {
        "verification_not_passed"
    } else if matches!(execution, Some("failed" | "outcome_unknown")) {
        "execution_not_completed"
    } else if continuous_waiting {
        "observing"
    } else if execution == Some("succeeded") {
        "verifying"
    } else {
        "working"
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn checks_daemon_support_before_creating_any_goal() -> Result<()> {
        let old = json!({"service":"telos"});
        let mut plan = VerificationPlan {
            checks: vec![],
            log_checks: vec![],
            test_checks: vec![serde_json::from_value(
                json!({"criterion_id":"test","command":{"program":"/bin/true","args":[],"readable_roots":[],"timeout_seconds":1,"max_output_bytes":1024}}),
            )?],
        };
        validate_capabilities(&plan, &old)?;
        plan.test_checks[0].adapter = "local.sandbox_json".into();
        assert!(validate_capabilities(&plan, &old).is_err());
        validate_capabilities(
            &plan,
            &json!({"verification_adapters":["local.sandbox_json"]}),
        )?;
        assert!(validate_capabilities(
            &plan,
            &json!({"mode":"recovery_review","verification_adapters":["local.sandbox_json"]})
        )
        .is_err());
        Ok(())
    }

    #[test]
    fn managed_failures_are_not_reported_as_running() {
        let schedule = json!({"armed":false});
        assert_eq!(
            progress_stage("paused", false, None, &schedule, false),
            "paused"
        );
        assert_eq!(
            progress_stage("active", true, None, &schedule, false),
            "verification_not_passed"
        );
        assert_eq!(
            progress_stage("active", false, Some("outcome_unknown"), &schedule, false),
            "execution_not_completed"
        );
    }

    #[test]
    fn continuous_goal_returns_to_observation_after_its_cycle_closes() {
        let schedule = json!({"armed":true});
        assert_eq!(
            progress_stage("active", false, Some("succeeded"), &schedule, true),
            "observing"
        );
        // A historical succeeded worker does not prove the next open cycle has
        // finished. Older daemons omit active_cycle_id, so keep the prior stage.
        assert_eq!(
            progress_stage("active", false, Some("succeeded"), &schedule, false),
            "verifying"
        );
    }
}
